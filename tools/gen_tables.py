#!/usr/bin/env python3
"""Emit src/tables.h from the authoritative ggml-common.h tables.

The IQ* codebook tables are part of the file format. They cannot be
reconstructed by hand: a single wrong entry yields a plausible-looking but
wrong tensor, i.e. a model that speaks fluent nonsense. So this script reads
the table text verbatim out of ggml-common.h and re-emits it, and the
generated header carries a checksum of the source rows so a future re-run can
prove it saw the same bytes.
"""
import re, sys, hashlib, pathlib

SRC = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "ref/ggml-common.h")
OUT = pathlib.Path(sys.argv[2] if len(sys.argv) > 2 else "src/tables.h")
text = SRC.read_text()

def rows(decl):
    i = text.index(decl)
    j = text.index("GGML_TABLE_END()", i)
    body = text[text.index("\n", i) + 1:j]
    return [int(t, 0) for t in re.findall(r"-?(?:0x)?[0-9a-fA-F]+", body)]

def emit(ctype, name, vals, per=16, fmt="0x%02x"):
    out = ["static const %s %s[%d] = {" % (ctype, name, len(vals))]
    for s in range(0, len(vals), per):
        out.append("    " + " ".join((fmt + ",") % v for v in vals[s:s + per]))
    out.append("};")
    return "\n".join(out), hashlib.sha256((",".join(map(str, vals)) + "\n").encode()).hexdigest()[:16]

# kvalues_iq4nl is signed; iq3s_grid is a uint32 table of four packed 3-bit
# magnitudes (values 1,3,..,15 stored directly as bytes).
kv = rows("GGML_TABLE_BEGIN(int8_t, kvalues_iq4nl, 16)")
assert len(kv) == 16, len(kv)
gr = rows("GGML_TABLE_BEGIN(uint32_t, iq3s_grid, 512)")
assert len(gr) == 512, len(gr)
bset = {b for w in gr for b in ((w >> (8 * k)) & 0xFF for k in range(4))}
assert bset <= set(range(1, 16, 2)), sorted(bset)

t_kv, h_kv = emit("uint8_t", "qe_kvalues_iq4nl", [v & 0xFF for v in kv], 16, "0x%02x")
t_gr, h_gr = emit("uint32_t", "qe_iq3s_grid", gr, 8, "0x%08x")

OUT.write_text("""/* GENERATED by tools/gen_tables.py from %s -- do not edit.
 *
 *   sha256(kvalues_iq4nl) = %s
 *   sha256(iq3s_grid)     = %s
 *
 * Rerun `python3 tools/gen_tables.py ref/ggml-common.h src/tables.h` after
 * refreshing ref/.
 */
#ifndef QE_TABLES_H
#define QE_TABLES_H
#include <stdint.h>

/* IQ4_NL / IQ4_XS codebook: w = d * kvalues_iq4nl[nibble]. */
%s

/* IQ3_S codebook: each entry holds four 3-bit magnitudes (1,3,..,15) packed
 * little-endian into a uint32, so a single vpgatherdd fetches four weights.
 * The sign of each weight lives in block_iq3_s.signs, not in the grid. */
%s

#endif /* QE_TABLES_H */
""" % (SRC.name, h_kv, h_gr, t_kv, t_gr))
print("wrote %s: kvalues_iq4nl[16] iq3s_grid[512]" % OUT)
