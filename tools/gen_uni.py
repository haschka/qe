#!/usr/bin/env python3
"""Generate src/uni_table.h: the Unicode categories the qwen35 BPE splitter needs.

The splitter in src/tok.c mirrors llama.cpp's
unicode_regex_split_custom_qwen35, which asks four questions per codepoint:
is_letter (L*), is_accent_mark (M*), is_number (N*), is_whitespace (the Unicode
White_Space property), and "is it assigned at all" (category != Cn), plus the
lower-case folds that can land on one of the letters of a contraction
('s|'t|'re|'ve|'m|'ll|'d).

Everything comes from the host's Unicode database, so the table is reproducible:

    python3 tools/gen_uni.py > src/uni_table.h
"""

import sys
import unicodedata

F_LETTER = 1
F_MARK = 2
F_NUMBER = 4
F_SPACE = 8
F_KNOWN = 16

# The Unicode White_Space property. Python's str.isspace is not it: isspace also
# covers the C0/C1 separators U+001C..U+001F, which the regex engine does not
# treat as whitespace.
WS = set(
    map(
        ord,
        "\t\n\v\f\r \x85\xa0\u1680\u2000\u2001\u2002\u2003\u2004\u2005\u2006"
        "\u2007\u2008\u2009\u200a\u2028\u2029\u202f\u205f\u3000",
    )
)

MAX = 0x110000
BLOCK = 256

flags = bytearray(MAX)
for cp in range(MAX):
    cat = unicodedata.category(chr(cp))
    if cat == "Cn":
        continue
    f = F_KNOWN
    if cat[0] == "L":
        f |= F_LETTER
    elif cat[0] == "M":
        f |= F_MARK
    elif cat[0] == "N":
        f |= F_NUMBER
    if cp in WS:
        f |= F_SPACE
    flags[cp] = f

# Deduplicate 256-codepoint blocks: Unicode is mostly runs, so a few hundred
# distinct blocks cover the whole range and lookup stays O(1).
nblk = (MAX + BLOCK - 1) // BLOCK
seen = {}
order = []
index = []
for b in range(nblk):
    key = bytes(flags[b * BLOCK:(b + 1) * BLOCK])
    if key not in seen:
        seen[key] = len(order)
        order.append(key)
    index.append(seen[key])

# Lower-case folds that reach an ASCII letter used by the contraction rule. The
# plain A-Z ones are handled inline; this catches full-width and ligature forms.
CONTRACT = set("stmdrvl")
fold = {}
for cp in range(0x21, MAX):
    lo = chr(cp).lower()
    if len(lo) == 1 and lo in CONTRACT and cp != ord(lo):
        fold[cp] = ord(lo)

w = sys.stdout.write
w("/* generated by tools/gen_uni.py - do not edit */\n")
w("#ifndef QE_UNI_TABLE_H\n#define QE_UNI_TABLE_H\n\n")
w("#include <stdint.h>\n\n")
w("enum { UNI_LETTER = %d, UNI_MARK = %d, UNI_NUMBER = %d, UNI_SPACE = %d, UNI_KNOWN = %d };\n\n"
  % (F_LETTER, F_MARK, F_NUMBER, F_SPACE, F_KNOWN))
w("#define UNI_BLOCK_SIZE %d\n" % BLOCK)
w("#define UNI_BLOCK_MASK (UNI_BLOCK_SIZE - 1)\n")
w("#define UNI_NBLK %d\n" % len(order))
w("#define UNI_NIDX %d\n\n" % nblk)
w("/* which block of uni_block covers each 256-codepoint range */\n")
w("static const uint16_t uni_index[UNI_NIDX] = {\n")
for i in range(0, nblk, 16):
    w("    " + ",".join(str(x) for x in index[i:i + 16]) + ",\n")
w("};\n\n")
w("static const uint8_t uni_block[UNI_NBLK][UNI_BLOCK_SIZE] = {\n")
for key in order:
    w("    { %s },\n" % ",".join(str(x) for x in key))
w("};\n\n")
w("/* category flags of a codepoint; 0 when unassigned or out of range */\n")
w("static inline uint8_t uni_flags(uint32_t cpt) {\n")
w("    if ((cpt >> 8) >= UNI_NIDX) return 0;\n")
w("    return uni_block[uni_index[cpt >> 8]][cpt & UNI_BLOCK_MASK];\n")
w("}\n\n")
w("/* lower case folds that reach a contraction letter; ASCII A-Z is implicit */\n")
w("static const uint32_t uni_fold_cpt[] = { %s };\n" % ",".join(str(k) for k in sorted(fold)))
w("static const uint8_t uni_fold_lo[] = { %s };\n" % ",".join(str(fold[k]) for k in sorted(fold)))
w("#define UNI_NFOLD %d\n\n" % len(fold))
w("static inline uint32_t uni_tolower32(uint32_t cpt) {\n")
w("    if (cpt >= 'A' && cpt <= 'Z') return cpt + (uint32_t) ('a' - 'A');\n")
w("    for (int i = 0; i < UNI_NFOLD; i++)\n")
w("        if (uni_fold_cpt[i] == cpt) return uni_fold_lo[i];\n")
w("    return cpt;\n}\n\n")
w("#endif\n")
sys.stderr.write("uni_table: %d blocks, %d ranges, %d folds\n" % (len(order), nblk, len(fold)))
